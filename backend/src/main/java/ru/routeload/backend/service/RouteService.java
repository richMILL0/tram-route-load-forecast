    public boolean containsRoute(int routeId) {
        return ROUTES.stream().anyMatch(route -> route.id() == routeId);
    }

    public Mono<RouteCollection> getRoutes() {
        var features = ROUTES.stream()
                .map(route -> new RouteFeature(
                        "Feature",
                        new RouteFeature.RouteGeometry("LineString", java.util.Arrays
                                .stream(route.coordinates())
                                        .map(point -> List.of(point[0], point[1]))
                                                .toList()
                        ),
                        new RouteFeature.RouteProperties(route.id(), route.name())
                ))
                .toList();

        return Mono.just(new RouteCollection("FeatureCollection", features));
    }
